#Ejemplo de tipo de datos en python

#tipo entero:
edad = 23
print("Edad",edad)

#Número con punto flotante (número decimal)
altura = 1.82
print("Altura:", altura)

#Cadena de texto
nombre = "Jair"
print("Nombre:", nombre)#

#Tipo Booleano
es_estudiante = True
print("¿Es estudiante?", es_estudiante)
es_villano = False
print("¿Es villano?", es_villano)

#None, ausencia de valor
dirección = None
print("Dirección: ", dirección)
