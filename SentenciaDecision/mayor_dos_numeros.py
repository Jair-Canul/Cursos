print(f'*** El mayor de 2 Números ***')

numero1 = int(input('Digite el primer número: '))
numero2 = int(input('Digite otro número: '))

if numero1 > numero2:
    print(f'''El numero mayor entre: {numero1} y {numero2} 
    es el {numero1}''')
else:
    print(f'''El numero mayor entre: {numero1} y {numero2} 
    es el {numero2}''')