print('*** Operadores Asignación Compuesto ***')
a, b = 10, 15
print(f'Valor inicial a: {a}, b :{b}')

#Operador compuesto dd suma +=
a += b #a=a+b
print(f'Operador a += b es: {a}')

#Operador compuesto de resta -=
a = 10 #reiniciamos la variable a
a -= b
print(f'Operador a -= b es:{a}')

#operado compuesto de multiplicación *=
a = 10 #reiniciamos el valor de la a
a *= b
print(f'operador a*=b es: {a}')

#operador compuesto de división
a = 10 #reiniciamos el valor de a
a /= b
print(f'operador a/=b es: {a}')

