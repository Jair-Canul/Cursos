print('*** Operadores Comparación (Relacionales) ***')
a, b = 7, 5
print(f'Valores iniciales de a: {a}, b: {b}')

#Operador igualdad ==
resultado = a == b
print(f'Resultado a == b: {resultado}')

#Operador diferente !=
resultado = a != b
print(f'Resultado a!=b: {resultado}')

#Operador mayor que >
resultado = a > b
print(f'Resultado a > b: {resultado}')

#operador  mayor o igua que >=
resultado = a >= b
print(f'Resultado a >=b : {resultado}')

#Operador menor que <=
resultado = a < b
print(f'Resultado a < b: {resultado}')

#Operador menor o igual que <=
resultado = a <= b
print(f'Resultado a <= b: {resultado}')