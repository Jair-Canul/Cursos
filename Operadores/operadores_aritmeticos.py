#Operadores aritméticos

a = 10
b = 3

#Suma
suma = a+b
print(f'suma: {suma}')

#Resta
resta = a-b
print(f'resta: {resta}')

#Multiplicación
multiplicacion= a * b
print(f'multiplicación: {multiplicacion}')

#división
division = a/b
print(f'división: {division: .2f}')

#División entera
division_entera = a//b
print(f'división: entera: {division_entera}')

#Módulo
modulo = a % b
print(f'módulo: {modulo}')

#Exponente
exponente = a**b
print(f'exponente: {exponente}')
